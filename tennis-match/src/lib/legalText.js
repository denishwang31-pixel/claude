/**
 * 남아 있는 빈칸 — 하나라도 있으면 출시하면 안 된다.
 *
 * 왜 두 가지를 따로 보나
 *   처음에는 겹대괄호만 찾았는데, 대괄호를 **하나씩만** 지운 상태를 놓쳤다.
 *   그러면 겹대괄호 검사는 통과하지만 문서에는 안내 문구가 그대로 남는다.
 *   ("· 대표자: 대표자 이름" 같은 꼴로 스토어에 올라간다)
 *   실제로 그렇게 "빈칸 없음 — 출시 가능" 이 뜬 적이 있다.
 *
 *   그래서 이제 둘 다 본다.
 *     1) 대괄호가 겹쳐 남아 있는가 (`[[` 또는 `]]`)
 *     2) 안내 문구 자체가 아직 문서에 있는가
 *
 *   본문에는 `[더보기]`, `[계정 삭제]` 처럼 화면 이름을 가리키는 대괄호가
 *   정상적으로 쓰인다. 그래서 홑대괄호는 잡지 않는다 — 잡으면 헛경보만 난다.
 */
export function pendingBlanks(text = `${TERMS}\n${PRIVACY}`) {
  const body = String(text);
  const found = [];

  /* 1) 겹대괄호가 남아 있다 — 아예 손대지 않았거나 반만 지웠다 */
  (body.match(/\[\[[^\]\n]*\]?\]?/g) || []).forEach((h) => found.push(h.trim()));
  if (/\]\]/.test(body)) {
    (body.match(/\[?\[?[^\[\n]*\]\]/g) || []).forEach((h) => found.push(h.trim()));
  }

  /* 2) 안내 문구가 그대로 남아 있다 — 대괄호만 지우고 값은 안 넣었다 */
  Object.values(BLANKS).forEach((label) => {
    if (body.includes(label)) found.push(`아직 안 채움: ${label}`);
  });

  return [...new Set(found)];
}

